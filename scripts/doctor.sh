#!/bin/sh
# Check the firmware toolchain against docker/toolchain.lock (run by `make doctor`).
#
#   sh scripts/doctor.sh           check, exit non-zero on any mismatch
#   sh scripts/doctor.sh --update  rewrite docker/toolchain.lock from what is installed
#
# The toolchain lives in TI_INSTALL_DIR (default ~/ti, /opt/ti in the container from
# docker/Dockerfile.am335x). Each component is identified by a hash over the sorted
# list of its files' SHA-256 sums and its symbolic links, so any added, removed or
# changed file shows up. Needs GNU find, sort, xargs and sha256sum (the container has
# them); on macOS run it through the container: docker/am335x.sh make doctor
set -u

ti=${TI_INSTALL_DIR:-$HOME/ti}
lock=$(dirname "$0")/../docker/toolchain.lock
components="gcc-arm-none-eabi-4_9-2015q3 xdctools_3_32_01_22_core bios_6_46_05_55 pdk_am335x_1_0_8"
gcc_expected="arm-none-eabi-gcc (GNU Tools for ARM Embedded Processors) 4.9.3 20150529 (release) [ARM/embedded-4_9-branch revision 227977]"
tiimage=$ti/pdk_am335x_1_0_8/packages/ti/starterware/tools/ti_image/tiimage_bin/tiimage

fail=0
ok() { printf '  ok    %s\n' "$*"; }
bad() { printf '  FAIL  %s\n' "$*"; fail=1; }

tree_hash() {
  (
    cd "$1" || exit 1
    find . -type f -print0 | LC_ALL=C sort -z | xargs -0 -r sha256sum
    find . -type l -print0 | LC_ALL=C sort -z | xargs -0 -r -n1 sh -c 'printf "%s -> %s\n" "$0" "$(readlink "$0")"'
  ) | sha256sum | cut -d' ' -f1
}

if [ ! -d "$ti" ]; then
  echo "doctor: TI_INSTALL_DIR '$ti' does not exist."
  echo "        The firmware toolchain is x86 Linux only; use the container: docker/am335x.sh make doctor"
  exit 1
fi

if [ "${1:-}" = "--update" ]; then
  {
    echo "# Firmware toolchain components installed by docker/Dockerfile.am335x."
    echo "# Generated by: sh scripts/doctor.sh --update (inside the container)."
    echo "# <tree hash>  <directory under TI_INSTALL_DIR>"
    for c in $components; do
      printf '%s  %s\n' "$(tree_hash "$ti/$c")" "$c"
    done
  } > "$lock"
  echo "doctor: wrote $lock"
  exit 0
fi

echo "Firmware toolchain in $ti"

gcc_actual=$("$ti/gcc-arm-none-eabi-4_9-2015q3/bin/arm-none-eabi-gcc" --version 2>/dev/null | head -n 1)
if [ "$gcc_actual" = "$gcc_expected" ]; then
  ok "arm-none-eabi-gcc: $gcc_actual"
else
  bad "arm-none-eabi-gcc: expected '$gcc_expected', got '${gcc_actual:-nothing}'"
fi

if [ -x "$tiimage" ]; then
  ok "tiimage: $tiimage"
else
  bad "tiimage missing: $tiimage"
fi

for c in $components; do
  expected=$(awk -v c="$c" '$2 == c { print $1 }' "$lock")
  if [ ! -d "$ti/$c" ]; then
    bad "$c: not installed"
    continue
  fi
  actual=$(tree_hash "$ti/$c")
  if [ -z "$expected" ]; then
    bad "$c: no entry in docker/toolchain.lock"
  elif [ "$actual" = "$expected" ]; then
    ok "$c: $actual"
  else
    bad "$c: tree hash $actual, expected $expected"
  fi
done

echo "Build tools"
for t in make python3 zip git swig; do
  if command -v "$t" >/dev/null 2>&1; then
    case $t in
      swig) v=$(swig -version | sed -n 's/^SWIG Version //p') ;;
      zip) v=$(zip -v | sed -n 's/^This is \(Zip [^ ]*\).*/\1/p') ;;
      *) v=$("$t" --version 2>&1 | head -n 1) ;;
    esac
    ok "$t: $v"
  else
    bad "$t: not found"
  fi
done

if [ $fail -ne 0 ]; then
  echo "doctor: toolchain does not match docker/toolchain.lock"
  exit 1
fi
echo "doctor: toolchain matches docker/toolchain.lock"
